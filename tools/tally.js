#!/usr/bin/env node
// Tally the cards in content/ and where the app uses each one.
//
//   node tools/tally.js            print a summary
//   node tools/tally.js --write    also rewrite docs/CONTENT_TALLY.md
//
// A card counts as "in use" when its path appears in one of the app's
// data files: the Library menu (web/nav-data.js), the default Action-view
// plan (web/default-plan.js) or the Qalb view (web/qalb-data.js).
// Anything else is a draft or unlisted card that no screen links to yet.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCES = {
  Library: 'web/nav-data.js',
  Plan: 'web/default-plan.js',
  Qalb: 'web/qalb-data.js',
};

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : e.name.endsWith('.md') ? [p] : [];
  });
}
const rel = p => path.relative(ROOT, p).split(path.sep).join('/');

// content/kalima/ holds glossary entries (the tap-a-word notes), not cards.
const all = walk(path.join(ROOT, 'content')).map(rel).sort();
const isGlossary = c => c.startsWith('content/kalima/');
const cards = all.filter(c => !isGlossary(c));
const glossary = all.filter(c => isGlossary(c) && !c.endsWith('_TEMPLATE.md'));

// Every content/...md path each data file mentions (comments stripped,
// so example paths in a header comment don't count).
const refs = {};
for (const [name, file] of Object.entries(SOURCES)) {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');
  refs[name] = new Set((src.match(/content\/[^'"`?#\s)]+\.md/g) || []).map(decodeURI));
}

const usedBy = c => Object.keys(SOURCES).filter(n => refs[n].has(c));
const inUse = cards.filter(c => usedBy(c).length);
const unused = cards.filter(c => !usedBy(c).length);
const missing = Object.entries(refs).flatMap(([n, set]) =>
  [...set].filter(p => !fs.existsSync(path.join(ROOT, p))).map(p => `${p} (in ${SOURCES[n]})`));

// Group by top-level folder (01-dua, 02-salah, …) for the per-section table.
const section = c => c.split('/')[1].endsWith('.md') ? '(root of content/)' : c.split('/')[1];
const sections = [...new Set(cards.map(section))];

const today = new Date().toISOString().slice(0, 10);
const lines = [];
lines.push('# Content tally', '');
lines.push(`Generated by \`node tools/tally.js --write\` on ${today}. Do not edit by hand.`, '');
lines.push(`**${cards.length} cards** in \`content/\`. **${inUse.length} in use**, ${unused.length} not linked from any screen. Plus ${glossary.length} glossary entries in \`content/kalima/\`.`, '');
lines.push('| Screen | Cards it links to |', '|---|---|');
for (const n of Object.keys(SOURCES)) {
  lines.push(`| ${n} (\`${SOURCES[n]}\`) | ${cards.filter(c => refs[n].has(c)).length} |`);
}
lines.push('', '## By section', '', '| Section | Cards | In use | Not linked |', '|---|---|---|---|');
for (const s of sections) {
  const cs = cards.filter(c => section(c) === s);
  const u = cs.filter(c => usedBy(c).length).length;
  lines.push(`| ${s} | ${cs.length} | ${u} | ${cs.length - u} |`);
}
lines.push(`| **Total** | **${cards.length}** | **${inUse.length}** | **${unused.length}** |`);

lines.push('', '## Not linked from any screen', '');
lines.push(unused.length ? unused.map(c => `- [${c}](../${c})`).join('\n') : 'None.');

lines.push('', '## Linked but missing', '', 'Paths a data file points to that have no file behind them.', '');
lines.push(missing.length ? missing.map(m => `- ${m}`).join('\n') : 'None.');

lines.push('', '## Every card', '', '| Card | Library | Plan | Qalb |', '|---|---|---|---|');
for (const c of cards) {
  const u = usedBy(c);
  lines.push(`| [${c.replace(/^content\//, '')}](../${c}) | ${['Library', 'Plan', 'Qalb'].map(n => u.includes(n) ? '✓' : '').join(' | ')} |`);
}
const md = lines.join('\n') + '\n';

console.log(`${cards.length} cards, ${inUse.length} in use, ${unused.length} not linked, ${missing.length} broken links (+${glossary.length} glossary entries)`);
for (const n of Object.keys(SOURCES)) console.log(`  ${n.padEnd(8)} ${cards.filter(c => refs[n].has(c)).length}`);
if (missing.length) console.log('Broken links:\n  ' + missing.join('\n  '));
if (process.argv.includes('--write')) {
  fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'docs/CONTENT_TALLY.md'), md);
  console.log('wrote docs/CONTENT_TALLY.md');
}
